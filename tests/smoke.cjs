const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.locator('[data-tab="settings"]').click();
  await page.locator('#startDate').fill('2026-11-20');
  await page.locator('#people').fill('5');
  await page.locator('#saveSettings').click();
  await page.reload();
  await page.locator('[data-tab="settings"]').click();
  assert.equal(await page.locator('#people').inputValue(),'5');
  assert.equal(await page.locator('#startDate').inputValue(),'2026-11-20');
  await page.locator('[data-tab="days"]').click();
  await page.getByRole('button',{name:'编辑',exact:true}).first().click();
  await page.locator('[name="hotel"]').fill('QA Hotel');
  await page.locator('#editForm button[type="submit"]').click();
  await page.reload();
  await page.locator('[data-tab="days"]').click();
  await page.getByText('QA Hotel').waitFor();
  await page.locator('[data-tab="settings"]').click();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'导出 JSON 备份'}).click()]);
  const fs=require('node:fs');const tmp=await download.path();
  const json=JSON.parse(fs.readFileSync(tmp,'utf8'));
  assert.equal(json.people,5);assert.equal(json.days[0].hotel,'QA Hotel');
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'清空并恢复默认行程'}).click();
  await page.reload();await page.locator('[data-tab="settings"]').click();
  assert.equal(await page.locator('#people').inputValue(),'4');
  page.once('dialog',d=>d.accept());
  await page.locator('#importFile').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(json))});
  await page.reload();await page.locator('[data-tab="settings"]').click();
  assert.equal(await page.locator('#people').inputValue(),'5');
  await page.locator('[data-tab="days"]').click();
  await page.getByText('QA Hotel').waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: mobile viewport, edit hotel, edit settings, save, refresh, download backup, reset and UI restore');
  console.log('NOTE: Chromium mobile emulation, not physical iPhone Safari');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
